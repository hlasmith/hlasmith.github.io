// Rebuilds feed.xml (RSS 2.0) from the posts in blog/.
// Run after adding or editing a post:  node tools/build-feed.js
// Reads each post's JSON-LD (headline, description, datePublished, author),
// its canonical URL and its shelf (.post-hero-meta). No dependencies.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SITE = 'https://hlasmith.co.uk';

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const unesc = s => String(s).replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'");
const rfc822 = d => new Date(d + 'T09:00:00Z').toUTCString();

const posts = fs.readdirSync(path.join(ROOT, 'blog')).filter(f => f.endsWith('.html')).map(f => {
  const html = fs.readFileSync(path.join(ROOT, 'blog', f), 'utf8');
  const ld = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)]
    .map(m => { try { return JSON.parse(m[1]); } catch (e) { return null; } })
    .find(j => j && /BlogPosting|Article/.test(j['@type']));
  if (!ld) throw new Error(f + ': no BlogPosting JSON-LD found');
  const canonical = (html.match(/<link rel="canonical" href="([^"]+)"/) || [])[1] || `${SITE}/blog/${f}`;
  const shelf = unesc(((html.match(/class="post-hero-meta">([^<]*)/) || [])[1] || '').trim());
  const author = (ld.author && ld.author.name) || 'Harrison Smith';
  return { title: ld.headline, description: ld.description, date: ld.datePublished, url: canonical, shelf, author };
}).sort((a, b) => b.date.localeCompare(a.date) || a.title.localeCompare(b.title));

const items = posts.map(p => `    <item>
      <title>${esc(p.title)}</title>
      <link>${esc(p.url)}</link>
      <guid isPermaLink="true">${esc(p.url)}</guid>
      <pubDate>${rfc822(p.date)}</pubDate>
      <dc:creator>${esc(p.author)}</dc:creator>${p.shelf ? `\n      <category>${esc(p.shelf)}</category>` : ''}
      <description>${esc(p.description)}</description>
    </item>`).join('\n');

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/build-feed.js. Do not edit by hand. -->
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:dc="http://purl.org/dc/elements/1.1/">
  <channel>
    <title>Harrison Smith: Writing</title>
    <link>${SITE}/writing.html</link>
    <atom:link href="${SITE}/feed.xml" rel="self" type="application/rss+xml"/>
    <description>Delivery, agile, tech, university and running. Managing life and writing about it.</description>
    <language>en-gb</language>
    <lastBuildDate>${rfc822(posts[0].date)}</lastBuildDate>
${items}
  </channel>
</rss>
`;
fs.writeFileSync(path.join(ROOT, 'feed.xml'), xml);
console.log(`feed.xml: ${posts.length} posts, newest ${posts[0].date}`);
